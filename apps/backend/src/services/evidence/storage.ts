import fs from "fs";
import path from "path";
import type { Readable } from "stream";
import { env } from "../../config/env";
import { createObjectStorage } from "./objectStorage";

// Private evidence storage behind one small interface: a local-disk adapter (default) and an
// S3-compatible object-storage adapter (EVIDENCE_STORAGE_DRIVER=s3). No route knows which one is in use.
export interface EvidenceStorage {
  put(key: string, data: Buffer): Promise<void>;
  stream(key: string): Promise<{ stream: Readable; size: number } | null>;
  remove(key: string): Promise<boolean>;
  exists(key: string): Promise<boolean>;
}

// apps/backend, so a relative folder such as "uploads" means the same place wherever the server is started from
const BACKEND_ROOT = path.resolve(__dirname, "../../..");

export class LocalDiskStorage implements EvidenceStorage {
  private readonly root: string;

  constructor(rootDir: string) {
    this.root = path.isAbsolute(rootDir) ? path.resolve(rootDir) : path.resolve(BACKEND_ROOT, rootDir);
  }

  get directory(): string {
    return this.root;
  }

  // Creates the evidence folder (and parents) when it does not exist yet.
  async ensureDirectory(): Promise<void> {
    await fs.promises.mkdir(this.root, { recursive: true });
  }

  // Keys are generated by the server, but a key is still never trusted: refuse anything that
  // would leave the storage root (path traversal).
  private resolve(key: string): string | null {
    if (!key || key.includes("\0")) return null;
    const resolved = path.resolve(this.root, key);
    if (resolved !== this.root && !resolved.startsWith(this.root + path.sep)) return null;
    return resolved;
  }

  async put(key: string, data: Buffer): Promise<void> {
    const file = this.resolve(key);
    if (!file) throw new Error("Invalid evidence key.");
    await fs.promises.mkdir(path.dirname(file), { recursive: true });
    await fs.promises.writeFile(file, data);
  }

  async stream(key: string): Promise<{ stream: Readable; size: number } | null> {
    const file = this.resolve(key);
    if (!file) return null;
    try {
      const stat = await fs.promises.stat(file);
      if (!stat.isFile()) return null;
      return { stream: fs.createReadStream(file), size: stat.size };
    } catch {
      return null;
    }
  }

  async remove(key: string): Promise<boolean> {
    const file = this.resolve(key);
    if (!file) return false;
    try {
      await fs.promises.unlink(file);
      return true;
    } catch {
      return false;
    }
  }

  async exists(key: string): Promise<boolean> {
    const file = this.resolve(key);
    if (!file) return false;
    try {
      return (await fs.promises.stat(file)).isFile();
    } catch {
      return false;
    }
  }
}

let instance: EvidenceStorage | null = null;

export function getEvidenceStorage(): EvidenceStorage {
  if (instance) return instance;
  if (env.evidenceStorageDriver === "s3") {
    instance = createObjectStorage({
      bucket: env.evidenceS3Bucket,
      region: env.evidenceS3Region,
      endpoint: env.evidenceS3Endpoint,
      forcePathStyle: env.evidenceS3ForcePathStyle,
      prefix: env.evidenceS3Prefix,
    });
    return instance;
  }
  if (env.evidenceStorageDriver !== "local") {
    throw new Error(`EVIDENCE_STORAGE_DRIVER="${env.evidenceStorageDriver}" is not supported. Use "local" or "s3".`);
  }
  instance = new LocalDiskStorage(env.evidenceStorageDir);
  return instance;
}

// Called once at server start: makes sure the evidence folder exists.
export async function prepareEvidenceStorage(): Promise<string | null> {
  const storage = getEvidenceStorage();
  if (storage instanceof LocalDiskStorage) {
    await storage.ensureDirectory();
    return storage.directory;
  }
  return null;
}

// For tests: use a different storage (for example a temp folder).
export function setEvidenceStorage(storage: EvidenceStorage | null): void {
  instance = storage;
}
