import type { Readable } from "stream";
import type { EvidenceStorage } from "./storage";

// The part of the AWS SDK client this adapter uses. Tests pass a fake with the same shape.
export interface ObjectStoreClient {
  send(command: unknown): Promise<any>;
}

// The command classes are injected so this file does not load the SDK until object storage is actually used.
export interface ObjectStoreCommands {
  PutObjectCommand: new (input: Record<string, unknown>) => unknown;
  GetObjectCommand: new (input: Record<string, unknown>) => unknown;
  HeadObjectCommand: new (input: Record<string, unknown>) => unknown;
  DeleteObjectCommand: new (input: Record<string, unknown>) => unknown;
}

export interface ObjectStorageOptions {
  bucket: string;
  /** optional folder inside the bucket, for example "evidence" */
  prefix?: string;
}

function isNotFound(err: unknown): boolean {
  const e = err as { name?: string; Code?: string; $metadata?: { httpStatusCode?: number } } | null;
  return e?.name === "NoSuchKey" || e?.name === "NotFound" || e?.Code === "NoSuchKey" || e?.$metadata?.httpStatusCode === 404;
}

// Private evidence in an S3-compatible bucket (AWS S3, Google Cloud Storage through its S3 interoperability
// endpoint, MinIO). The bucket must block public access: files are only ever served through the API's
// signed, expiring links, never by a bucket address.
export class ObjectStorage implements EvidenceStorage {
  private readonly prefix: string;

  constructor(
    private readonly client: ObjectStoreClient,
    private readonly commands: ObjectStoreCommands,
    private readonly options: ObjectStorageOptions
  ) {
    this.prefix = (options.prefix ?? "").replace(/^\/+|\/+$/g, "");
  }

  // Keys are generated by the server, but a key is still never trusted (same rule as the local adapter).
  private objectKey(key: string): string | null {
    if (!key || key.includes("\0") || key.includes("\\") || key.startsWith("/")) return null;
    if (key.split("/").some((part) => part === ".." || part === ".")) return null;
    return this.prefix ? `${this.prefix}/${key}` : key;
  }

  private ref(key: string) {
    return { Bucket: this.options.bucket, Key: key };
  }

  async put(key: string, data: Buffer): Promise<void> {
    const objectKey = this.objectKey(key);
    if (!objectKey) throw new Error("Invalid evidence key.");
    await this.client.send(new this.commands.PutObjectCommand({ ...this.ref(objectKey), Body: data, ContentLength: data.length }));
  }

  async stream(key: string): Promise<{ stream: Readable; size: number } | null> {
    const objectKey = this.objectKey(key);
    if (!objectKey) return null;
    try {
      const res = await this.client.send(new this.commands.GetObjectCommand(this.ref(objectKey)));
      if (!res?.Body) return null;
      return { stream: res.Body as Readable, size: Number(res.ContentLength ?? 0) };
    } catch (err) {
      if (isNotFound(err)) return null;
      throw err; // a real outage must not look like "file missing"
    }
  }

  async exists(key: string): Promise<boolean> {
    const objectKey = this.objectKey(key);
    if (!objectKey) return false;
    try {
      await this.client.send(new this.commands.HeadObjectCommand(this.ref(objectKey)));
      return true;
    } catch (err) {
      if (isNotFound(err)) return false;
      throw err; // bad credentials or an unreachable bucket make /health/ready fail, as they should
    }
  }

  async remove(key: string): Promise<boolean> {
    const objectKey = this.objectKey(key);
    if (!objectKey) return false;
    if (!(await this.exists(key))) return false; // S3 deletes are silent for missing keys; report honestly
    await this.client.send(new this.commands.DeleteObjectCommand(this.ref(objectKey)));
    return true;
  }
}

export interface ObjectStorageEnv {
  bucket: string;
  region: string;
  endpoint: string;
  forcePathStyle: boolean;
  prefix: string;
}

// Builds the adapter with the real AWS SDK. Credentials come from the SDK's standard sources (AWS_ACCESS_KEY_ID /
// AWS_SECRET_ACCESS_KEY, or the platform's role). For Google Cloud Storage use an HMAC key pair in those two variables
// and EVIDENCE_S3_ENDPOINT=https://storage.googleapis.com.
export function createObjectStorage(cfg: ObjectStorageEnv): ObjectStorage {
  if (!cfg.bucket) throw new Error("EVIDENCE_S3_BUCKET must be set when EVIDENCE_STORAGE_DRIVER=s3.");
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const sdk = require("@aws-sdk/client-s3") as typeof import("@aws-sdk/client-s3");
  const client = new sdk.S3Client({
    region: cfg.region,
    ...(cfg.endpoint ? { endpoint: cfg.endpoint } : {}),
    forcePathStyle: cfg.forcePathStyle,
  });
  return new ObjectStorage(client as unknown as ObjectStoreClient, sdk as unknown as ObjectStoreCommands, {
    bucket: cfg.bucket,
    prefix: cfg.prefix,
  });
}
